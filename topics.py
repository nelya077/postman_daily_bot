# Готовые темы для меню: название кнопки -> основы слов для поиска в новостях.
# Совпадение идёт по началу слова, поэтому «наук» найдёт «наука», «науки», «научный».
PRESETS = {
    "Технологии": ["технолог", "нейросет", "искусственн", "ии", "программир", "гаджет", "смартфон", "python"],
    "Экономика": ["экономик", "инфляц", "рубл", "доллар", "ключев", "ставк", "бирж", "ввп"],
    "Бизнес": ["бизнес", "стартап", "компани", "инвестиц", "сделк"],
    "Наука": ["наук", "научн", "учёны", "ученые", "исследован", "физик", "биолог"],
    "Космос": ["космос", "космическ", "nasa", "роскосмос", "спутник", "ракет"],
    "Игры": ["видеоигр", "геймер", "playstation", "xbox", "steam", "nintendo"],
    "Спорт": ["спорт", "футбол", "хоккей", "теннис", "чемпионат", "матч"],
    "Кино": ["кино", "фильм", "сериал", "премьер", "режиссёр", "актёр"],
}

_LOWER = {name.lower(): stems for name, stems in PRESETS.items()}


def expand(topics: list[str]) -> list[str]:
    """Названия готовых тем превращает в набор основ, остальные слова оставляет как есть."""
    terms: list[str] = []
    for t in topics:
        t = t.strip().lower()
        if t:
            terms.extend(_LOWER.get(t, [t]))
    return terms
